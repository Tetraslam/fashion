// Parses the exported Claude lookbook artifact (no code execution) into
// data/lookbook.json: every product link, plus the 20 outfits that use them.
// usage: node scripts/extract-lookbook.mjs source/lookbook/Main.dc.html
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const src = readFileSync(process.argv[2] ?? "source/lookbook/Main.dc.html", "utf8");

const urls = {};
const uBlock = src.match(/const U = \{([\s\S]*?)\n\s*\};/)[1];
for (const m of uBlock.matchAll(/(\w+):\s*'([^']+)'/g)) urls[m[1]] = m[2];

const unquote = (s) => s.replace(/\\'/g, "'");
const shared = {};
for (const m of src.matchAll(/const (\w+) = P\('([^']+)', '([^']+)', U\.(\w+)\);/g)) {
  shared[m[1]] = { brand: m[2], item: m[3], url: urls[m[4]], key: m[4] };
}

const outfits = [];
const outfitRe =
  /\{ name: '([^']+)', vibe: '((?:[^'\\]|\\.)*)', c: \[([^\]]+)\],\s*pieces: \[([\s\S]*?)\] \}/g;
for (const m of src.matchAll(outfitRe)) {
  const pieces = [];
  for (const p of m[4].matchAll(/P\('([^']+)', '([^']+)', U\.(\w+)\)|\b([A-Z]{3})\b/g)) {
    if (p[1]) pieces.push({ brand: p[1], item: p[2], url: urls[p[3]], key: p[3] });
    else if (shared[p[4]]) pieces.push(shared[p[4]]);
  }
  outfits.push({
    name: m[1],
    vibe: unquote(m[2]),
    palette: [...m[3].matchAll(/'(#[0-9a-f]{6})'/gi)].map((c) => c[1]),
    pieces,
  });
}

const products = new Map();
for (const o of outfits) for (const p of o.pieces) if (!products.has(p.url)) products.set(p.url, p);

mkdirSync("data", { recursive: true });
writeFileSync(
  "data/lookbook.json",
  JSON.stringify({ products: [...products.values()], outfits }, null, 2) + "\n",
);
const md = [
  "# Lookbook links",
  "",
  "Every product link from the original Claude lookbook artifact (`source/lookbook/`), grouped by fit.",
  "Generated by `pnpm lookbook:extract`; the live data is in `data/`.",
  "",
  ...outfits.flatMap((o, i) => [
    `## ${String(i + 1).padStart(2, "0")} ${o.name}`,
    "",
    `${o.vibe}`,
    "",
    ...o.pieces.map((p) => `- **${p.brand}**: [${p.item}](${p.url})`),
    "",
  ]),
].join("\n");
writeFileSync("source/lookbook/LINKS.md", md);
console.log(`${Object.keys(urls).length} urls, ${products.size} unique products, ${outfits.length} outfits`);
